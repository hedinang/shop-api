package com.example.shop_api.model.entity;

import com.example.shop_api.configuration.AutoGeneratedUUId;
import lombok.AllArgsConstructor;
import lombok.Data;
import lombok.NoArgsConstructor;
import org.bson.types.ObjectId;
import org.springframework.data.mongodb.core.index.Indexed;
import org.springframework.data.mongodb.core.mapping.Document;
import org.springframework.data.mongodb.core.mapping.Field;
import org.springframework.data.mongodb.core.mapping.MongoId;

@Data
@Document(collection = "sim_package")
@AllArgsConstructor
@NoArgsConstructor
public class SimPackage extends MongoBaseEntity {
    @MongoId
    private ObjectId id;
    @Indexed(unique = true)
    @Field(name = "package_id")
    @AutoGeneratedUUId
    private String daySimId;
    @Field(name = "sim_id")
    private String simId;
    @Field(name = "name")
    private String name;
    @Field(name = "title")
    private String title;
    /* day in month */
    @Field(name = "time")
    private String time;
    @Field(name = "pack")
    private String pack;
    @Field(name = "unit")
    private String unit;
    /* e sim or normal sim*/
    private String type;
    /* vina, mobile, viettel v.v.v */
    private String brand;
    private String nation;
}
