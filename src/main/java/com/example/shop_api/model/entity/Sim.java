package com.example.shop_api.model.entity;

import com.example.shop_api.configuration.AutoGeneratedUUId;
import lombok.AllArgsConstructor;
import lombok.Data;
import lombok.NoArgsConstructor;
import org.bson.types.ObjectId;
import org.springframework.data.mongodb.core.index.Indexed;
import org.springframework.data.mongodb.core.mapping.Document;
import org.springframework.data.mongodb.core.mapping.Field;
import org.springframework.data.mongodb.core.mapping.MongoId;

import java.util.List;

@Data
@Document(collection = "sim")
@AllArgsConstructor
@NoArgsConstructor
public class Sim extends MongoBaseEntity {
    @MongoId
    private ObjectId id;
    @AutoGeneratedUUId
    @Indexed(unique = true)
    @Field(name = "sim_id")
    private String simId;
    @Field(name = "name")
    private String name;
    @Field(name = "title")
    private String title;
    @Field(name = "advantages")
    private List<String> advantages;
    /* e sim or normal sim*/
    private String type;
    /* vina, mobile, viettel v.v.v */
    private String brand;
    private String nation;
}
