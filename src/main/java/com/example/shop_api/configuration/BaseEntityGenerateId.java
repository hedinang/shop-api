package com.example.shop_api.configuration;

import com.example.shop_api.util.StringUtil;
import org.springframework.data.mongodb.core.mapping.event.BeforeConvertCallback;
import org.springframework.stereotype.Component;

import java.lang.reflect.Field;

@Component
public class BaseEntityGenerateId<T> implements BeforeConvertCallback<T> {

    @Override
    public T onBeforeConvert(T entity, String collection) {
        if (entity == null) {
            return null;
        }

        for (Field field : entity.getClass().getDeclaredFields()) {
            if (field.isAnnotationPresent(AutoGeneratedUUId.class)) {
                field.setAccessible(true);
                try {
                    Object value = field.get(entity);
                    if (value == null || value.toString().isEmpty()) {
                        field.set(entity, StringUtil.generateId());
                    }
                } catch (IllegalAccessException e) {
                    throw new RuntimeException("Failed to set auto-generated ID", e);
                }
            }
        }
        return entity;
    }
}
